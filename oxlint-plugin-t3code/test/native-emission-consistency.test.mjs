import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";
import * as fc from "fast-check";
import { compileProjectSync } from "vibelang/project";
import { expect, test } from "vite-plus/test";

const root = NodeURL.fileURLToPath(new URL("../../", import.meta.url));
const packages = [
  ["provider-grok", "status", true],
  ["provider-pi", "status", true],
  ["provider-acp", "nativeLogging", false],
  ["provider-core", "maintenanceResolver", false],
];

test.each(packages)(
  "keeps %s generated runtime output aligned with its source",
  (name, module, hasBody) => {
    const packageRoot = NodePath.resolve(root, "packages", name);
    const source = NodePath.resolve(packageRoot, "src/server", module + ".vibe");
    const header =
      "// Generated by vibelang from " +
      NodePath.relative(packageRoot, source).split(NodePath.sep).join("/") +
      "; the migrate flow writes it again with each batch.\n";
    const targets = [
      [source, NodePath.resolve(packageRoot, ".vibelang/js/src/server", module + ".js")],
      ...(hasBody
        ? [
            [
              NodePath.resolve(NodePath.dirname(source), module + ".vibe.platform.js"),
              NodePath.resolve(
                packageRoot,
                ".vibelang/js/src/server",
                module + ".vibe.platform.js",
              ),
            ],
          ]
        : []),
    ];
    const before = new Map(targets.map(([, file]) => [file, NodeFS.readFileSync(file, "utf8")]));
    const compiled = compileProjectSync({
      project: NodePath.resolve(packageRoot, "tsconfig.json"),
      root: packageRoot,
      cache: false,
    });
    expect(compiled.errors).toEqual([]);
    fc.assert(
      fc.property(
        fc.shuffledSubarray(targets, { minLength: targets.length, maxLength: targets.length }),
        fc.integer({ min: 0, max: 4 }),
        (order, dots) => {
          for (const [key, file] of order) {
            const aliasedKey = NodePath.resolve(
              root,
              ...Array(dots).fill("."),
              NodePath.relative(root, key),
            );
            const emitted = compiled.outputs.get(aliasedKey);
            expect(emitted, NodePath.relative(root, key)).toBeDefined();
            const actual = NodeFS.readFileSync(file, "utf8");
            expect(actual.startsWith(header), NodePath.relative(root, file)).toBe(true);
            expect(actual.slice(header.length), NodePath.relative(root, file)).toBe(emitted.code);
            expect(actual, "checking emitted output must not rewrite the artifact").toBe(
              before.get(file),
            );
          }
        },
      ),
    );
  },
);
